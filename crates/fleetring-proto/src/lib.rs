//! gRPC services and messages between FleetRing nodes (ADR-0019).
//!
//! Package `fleetring.v1` defines the `Control`, `Replication`, and `Database` services. Log
//! positions and batch payloads are opaque bytes that only engine adapters interpret, and
//! positions compare lexicographically in log order (ADR-0016).

/// The generated messages, clients, and servers for package `fleetring.v1`.
#[allow(
    missing_docs,
    unreachable_pub,
    clippy::all,
    clippy::allow_attributes_without_reason,
    reason = "generated by tonic-prost-build from fleetring.proto"
)]
pub mod v1 {
    tonic::include_proto!("fleetring.v1");
}

use v1::ProtocolVersion;

/// The protocol version this build speaks.
pub const PROTOCOL_VERSION: ProtocolVersion = ProtocolVersion { major: 1, minor: 0 };

/// The largest message a node sends or accepts: a replication batch or a snapshot chunk.
pub const MAX_MESSAGE_BYTES: usize = 64 * 1024 * 1024;

/// Checks a peer's protocol version at `Join`: peers must share the major version.
///
/// # Errors
///
/// A `FAILED_PRECONDITION` status naming both versions when the peer's major version differs, or
/// `INVALID_ARGUMENT` when the peer sent none.
pub fn check_protocol(peer: Option<&ProtocolVersion>) -> Result<(), tonic::Status> {
    let Some(peer) = peer else {
        return Err(tonic::Status::invalid_argument("missing protocol version"));
    };
    if peer.major == PROTOCOL_VERSION.major {
        Ok(())
    } else {
        Err(tonic::Status::failed_precondition(format!(
            "unsupported protocol version {}.{}: this node speaks {}.{}",
            peer.major, peer.minor, PROTOCOL_VERSION.major, PROTOCOL_VERSION.minor
        )))
    }
}
