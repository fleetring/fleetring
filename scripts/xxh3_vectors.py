"""Print XXH3-64 reference vectors for `crates/fleetring/tests/it/hasher.rs`.

The expected values come from the upstream C xxHash library, through the `xxhash` package
on PyPI, so they are independent of the Rust implementation under test.

    python3 -m venv .venv && .venv/bin/pip install xxhash
    .venv/bin/python scripts/xxh3_vectors.py
"""

import xxhash

# Lengths that exercise every XXH3-64 code path: 0, 1-3, 4-8, 9-16, 17-128, 129-240, >240.
LENGTHS = [0, 1, 3, 4, 8, 9, 16, 17, 128, 129, 240, 241, 1024]
SEEDS = [0, 1, 0x9E37_79B9_7F4A_7C15]


def pattern(length: int) -> bytes:
    """Input bytes: byte i is (31 * i + 7) mod 256."""
    return bytes((31 * i + 7) % 256 for i in range(length))


def main() -> None:
    print(f"// Generated by scripts/xxh3_vectors.py with python-xxhash {xxhash.VERSION}")
    print(f"// (C xxHash {xxhash.XXHASH_VERSION}).")
    for length in LENGTHS:
        for seed in SEEDS:
            digest = xxhash.xxh3_64_intdigest(pattern(length), seed=seed)
            print(f"    ({length}, 0x{seed:016x}, 0x{digest:016x}),")


if __name__ == "__main__":
    main()
